create table usuario (
    id         bigint generated by default as identity primary key,
    usuario    varchar(100) not null unique,
    senha_hash varchar(100) not null
);

create table cliente (
    id              bigint generated by default as identity primary key,
    projeto         varchar(200) not null,
    cliente         varchar(200),
    contato_nome    varchar(200),
    telefone        varchar(50),
    email           varchar(200),
    descricao       text,
    tipo_servico    varchar(30)  not null,
    status          varchar(30)  not null,
    data_inicio     date,
    data_fim        date,
    site            varchar(500),
    repositorio     varchar(500),
    hospedagem      varchar(500),
    arquivos        varchar(500),
    valor_projeto   numeric(12, 2),
    mensalidade     numeric(12, 2),
    dia_vencimento  integer,
    forma_pagamento varchar(30),
    proxima_acao    text,
    escopo          text
);

create table pagamento (
    id         bigint generated by default as identity primary key,
    cliente_id bigint           not null references cliente (id) on delete cascade,
    mes        varchar(7)     not null,
    valor      numeric(12, 2) not null,
    status     varchar(20)    not null
);

create table custo (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint           not null references cliente (id) on delete cascade,
    descricao   varchar(200)   not null,
    valor       numeric(12, 2) not null,
    recorrencia varchar(20)    not null
);

create table data_importante (
    id         bigint generated by default as identity primary key,
    cliente_id bigint         not null references cliente (id) on delete cascade,
    descricao  varchar(200) not null,
    data       date         not null
);

create table nota (
    id         bigint generated by default as identity primary key,
    cliente_id bigint not null references cliente (id) on delete cascade,
    data       date not null,
    texto      text not null
);

create index idx_pagamento_cliente on pagamento (cliente_id);
create index idx_custo_cliente on custo (cliente_id);
create index idx_data_importante_cliente on data_importante (cliente_id);
create index idx_nota_cliente on nota (cliente_id);
